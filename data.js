function formatINR(amount) {
  if (amount >= 10000000) return `₹${(amount / 10000000).toFixed(2)}Cr`;
  if (amount >= 100000) return `₹${(amount / 100000).toFixed(2)}L`;
  return `₹${amount.toLocaleString('en-IN')}`;
}

function getCarHealthScore(car) {
  let score = 100;
  const age = 2026 - car.year;
  score -= age * 5;
  score -= (car.km / 1000) * 0.5;
  if (car.ownership === '2nd') score -= 10;
  if (car.ownership === '3rd') score -= 20;
  return Math.max(20, Math.min(100, Math.round(score)));
}

function getHealthColor(score) {
  if (score >= 75) return '#10b981';
  if (score >= 50) return '#f59e0b';
  return '#ef4444';
}

function getVerdictBadgeClass(verdict) {
  if (verdict === 'Undervalued') return 'badge-value';
  if (verdict === 'Fair') return 'badge-fair';
  return 'badge-hot';
}

function getMaintenanceCost(car) {
  const base = { 'Very Low': 5000, 'Low': 8000, 'Medium': 15000, 'High': 25000 };
  const ageFactor = Math.max(1, (2026 - car.year) * 0.15 + 1);
  const kmFactor = car.km > 80000 ? 1.4 : car.km > 50000 ? 1.2 : 1.0;
  return Math.round((base[car.maintenance] || 10000) * ageFactor * kmFactor);
}
